/* build-pages.js  (optional helper, run with:  node build-pages.js)
   Copies the content of every page into js/pages.js. That bundle lets the site change pages
   WITHOUT reloading even when you double-click index.html (no web server), so music keeps playing.
   Under Live Server the real .html files are used, so you only need to re-run this after editing
   a page if you also want the double-click mode to show your changes. */
const fs = require('fs'), pages = {};
for (const f of fs.readdirSync('.').filter(f => f.endsWith('.html'))) {
  const s = fs.readFileSync(f, 'utf8');
  pages[f] = {
    title: (s.match(/<title>([\s\S]*?)<\/title>/) || [])[1] || '',
    page:  (s.match(/<body[^>]*data-page="([^"]+)"/) || [])[1] || '',
    html:  s.slice(s.indexOf('<main id="main">') + 16, s.indexOf('</main>'))
  };
}
fs.writeFileSync('js/pages.js', '/* Generated by build-pages.js. Page content for no-server mode. */\nwindow.SITE_PAGES = ' + JSON.stringify(pages) + ';\n');
console.log('js/pages.js written for', Object.keys(pages).join(', '));
